/**
 * Returns logo metadata for a client ID if available.
 * Resolves the logo path with assetUrl() for environment compatibility.
 */
export function getClientLogo(clientId) {
  const meta = clientLogos[clientId];
  if (!meta) return null;
  return {
    ...meta,
    src: assetUrl(meta.logo)
  };
}

/**
 * Unique list of featured clients with logos for showcase carousels/grids.
 */
export const featuredClientLogos = Object.entries(clientLogos).reduce((acc, [id, meta]) => {
  // Deduplicate by logo path so same institution (e.g. Vadtal or Dholera) is listed once in the marquee
  if (!acc.some((item) => item.logo === meta.logo)) {
    acc.push({
      id,
      ...meta,
      src: assetUrl(meta.logo)
    });
  }
  return acc;
}, []);

export default clientLogos;
